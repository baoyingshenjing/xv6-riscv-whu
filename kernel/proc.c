void
proc_mapstacks(pagetable_t kpgtbl)
{
  char *pa = kalloc();

  if (pa == 0)
    panic("proc_mapstacks");
  kvmmap(kpgtbl, KSTACK(0), (uint64)pa, PGSIZE, PTE_R | PTE_W);
}

void
procinit(void)
{
  proc.kstack = KSTACK(0);
}

int
cpuid(void)
{
  return r_tp();
}

struct cpu *
mycpu(void)
{
  return &cpus[cpuid()];
}

struct proc *
myproc(void)
{
  push_off();
  struct proc *p = mycpu()->proc;
  pop_off();
  return p;
}

// Grow or shrink the single process's user heap.  User pages below p->sz
// remain untouched; new pages are eagerly allocated in this stage.
int
growproc(int n)
{
  struct proc *p = myproc();
  uint64 sz = p->sz;

  if (n > 0) {
    if (sz + n < sz || sz + n >= TRAPFRAME)
      return -1;
    sz = uvmalloc(p->pagetable, sz, sz + n, PTE_W);
    if (sz == 0)
      return -1;
  } else if (n < 0) {
    if ((uint64)(-n) > sz)
      return -1;
    sz = uvmdealloc(p->pagetable, sz, sz + n);
  }

  p->sz = sz;
  return 0;
}

pagetable_t
proc_pagetable(struct proc *p)
{
  pagetable_t pagetable = uvmcreate();

  if (pagetable == 0)
    panic("proc_pagetable");
  if (mappages(pagetable, TRAMPOLINE, PGSIZE, (uint64)trampoline,
               PTE_R | PTE_X) != 0)
    panic("proc_pagetable: trampoline");
  if (mappages(pagetable, TRAPFRAME, PGSIZE, (uint64)p->trapframe,
               PTE_R | PTE_W) != 0)
    panic("proc_pagetable: trapframe");

  return pagetable;
}

static struct proc *
allocproc(void)
{
  struct proc *p = &proc;

  p->pid = 1;
  p->trapframe = (struct trapframe *)kalloc();
  if (p->trapframe == 0)
    panic("allocproc: trapframe");
  p->pagetable = proc_pagetable(p);
  memset(&p->context, 0, sizeof(p->context));
  p->context.ra = (uint64)usertrapret;
  p->context.sp = p->kstack + PGSIZE;
  return p;
}

void
userinit(void)
{
  struct proc *p = allocproc();
  char *mem;

  uvmfirst(p->pagetable, initcode, sizeof(initcode));

  // Pages 1 and 2 are zero-initialized global data; page 3 is the user stack.
  for (int page = 1; page <= 3; page++) {
    mem = kalloc();
    if (mem == 0)
      panic("userinit: user page");
    memset(mem, 0, PGSIZE);
    if (mappages(p->pagetable, page * PGSIZE, PGSIZE, (uint64)mem,
                 PTE_R | PTE_W | PTE_U) != 0)
      panic("userinit: mappages");
  }

  p->sz = 4 * PGSIZE;
  p->trapframe->epc = 0x2f8;
  p->trapframe->sp = 4 * PGSIZE;

  // No scheduler exists yet: make CPU 0 enter the first process directly.
  mycpu()->proc = p;
  swtch(&mycpu()->context, &p->context);
  panic("userinit returned");
}
